STUDIUM.methode('dissertation', {
  titre: 'La dissertation',
  resume: 'Philosophie, lettres, cinéma, géographie : la démarche commune',
  icone: 'pen-line',
  contenu: `
    La dissertation n'est pas un exposé de connaissances : c'est la **discussion argumentée d'un problème** que le sujet contient. Le correcteur évalue d'abord ta capacité à **poser** ce problème, puis à le **traiter** avec ordre et précision.

    ## 1. Analyser le sujet (environ 30 min sur 4 h)

    - Recopie le sujet en haut d'une feuille et **souligne chaque mot**.
    - Pour chaque terme important :
      - donne plusieurs **définitions** (sens courant, sens philosophique ou technique, étymologie) ;
      - cherche des **synonymes** et des **contraires** ;
      - note les **exemples** qui te viennent (œuvres, auteurs, films, lieux…).
    - Observe la **forme de la question** :
      - *Peut-on… ?* : est-ce possible (en fait) ? est-ce légitime (en droit) ?
      - *Faut-il… ?* : nécessité, obligation morale, utilité ?
      - *X est-il Y ?* : examine le lien entre deux notions.
      - Sujet-citation : qui parle, dans quel contexte, et que veut dire la phrase ?
    - Repère le **présupposé** : ce que le sujet tient pour acquis et que tu peux interroger.

    ## 2. Construire la problématique

    :::retenir Le cœur de la copie
    Une problématique fait apparaître une **tension** : deux réponses également défendables, ou une évidence qui se révèle fragile. Formule-la en une ou deux questions, sans en empiler cinq.
    :::

    :::exemple Exemple
    Sujet : *Peut-on tout connaître ?*
    - Évidence de départ : la science progresse sans cesse, rien ne semble lui échapper par principe.
    - Mais : connaître suppose un sujet fini (nos sens, notre raison ont des limites), et certains objets (soi-même, Dieu, l'avenir) semblent échapper à la connaissance.
    - Problématique : *Les limites de notre connaissance sont-elles seulement provisoires, ou tiennent-elles à la nature même de l'esprit humain ?*
    :::

    ## 3. Bâtir le plan

    - **Deux ou trois parties**, chacune avec **deux ou trois sous-parties**.
    - Le plan doit **progresser** : chaque partie répond aux limites de la précédente.
    - Types de plans :
      - **dialectique** : I. thèse — II. limites, antithèse — III. dépassement (le plus classique, à condition que la III ne soit pas un compromis mou) ;
      - **notionnel** : on distingue plusieurs sens d'une notion et on les examine du plus simple au plus exigeant ;
      - **thématique** (fréquent en géographie et en histoire) : on traite des aspects complémentaires.
    - Chaque sous-partie suit le schéma **idée → argument → exemple précis → mini-conclusion**.

    ## 4. Rédiger

    ### L'introduction (à rédiger entièrement au brouillon)
    1. **Accroche** : un exemple, une citation, un fait précis, en lien direct avec le sujet (pas de « De tout temps les hommes… »).
    2. **Présentation et analyse** du sujet : définition des termes.
    3. **Problématique**.
    4. **Annonce du plan**, claire et sobre.

    ### Le développement
    - Un paragraphe par sous-partie, avec un alinéa.
    - Des **transitions** : un bilan de la partie précédente et la question qui oblige à aller plus loin.
    - Des **références précises** : auteur, œuvre, date, passage. Une citation courte et exacte vaut mieux qu'une longue citation approximative.

    ### La conclusion
    - Bilan du parcours, **réponse nette** à la problématique.
    - Une ouverture est possible, si elle prolonge vraiment la réflexion.

    ## 5. Gérer son temps (DS de 4 h)

    | Étape | Durée conseillée |
    |---|---|
    | Analyse du sujet, recherche d'idées | 45 min |
    | Problématique et plan détaillé | 30 min |
    | Introduction au brouillon | 15 min |
    | Rédaction au propre | 2 h 15 |
    | Relecture | 15 min |

    :::attention Erreurs fréquentes
    - Réciter son cours sans répondre à la question.
    - Un plan « oui / non / peut-être ».
    - Des exemples vagues (« un auteur a dit… »).
    - Une conclusion qui pose une question nouvelle sans rapport.
    :::
  `
});

