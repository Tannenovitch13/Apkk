STUDIUM.methode('explication', {
  titre: 'L\'explication de texte',
  resume: 'Philosophie et littérature : expliquer sans paraphraser',
  icone: 'book-text',
  contenu: `
    Expliquer un texte, c'est **rendre explicite** ce qui est implicite : montrer **ce que dit** le texte, **comment** il le dit, et **pourquoi** cela compte. Le principe d'or : *le texte, tout le texte, rien que le texte* — éclairé par tes connaissances.

    ## 1. Comprendre
    - Lis le texte plusieurs fois. Repère :
      - le **thème** (de quoi il parle) ;
      - la **thèse** (ce que l'auteur affirme) ;
      - la **thèse adverse**, souvent implicite (contre qui il écrit) ;
      - les **concepts** et les **mots de liaison** (*car*, *donc*, *mais*, *or*).
    - Découpe le texte en **mouvements** et donne à chacun un titre qui dit ce qu'il **fait** (*l'auteur pose une définition*, *il réfute une objection*…).

    ## 2. Poser le problème
    - **En philosophie** : quelle question le texte résout-il ? Quel est l'**enjeu** (pourquoi est-ce important) ?
    - **En littérature** : formule un **projet de lecture** : *comment ce sonnet transforme-t-il la nostalgie en éloge de la terre natale ?*

    ## 3. Expliquer
    - Suis **l'ordre du texte**, mouvement par mouvement.
    - Pour chaque phrase importante :
      - **cite** précisément ;
      - **analyse** les mots (définitions, connotations) et les procédés (syntaxe, rythme, images, sonorités en poésie) ;
      - **explique** leur fonction dans l'argument ou dans l'effet produit ;
      - **interroge** : que suppose l'auteur ? une objection est-elle possible ?
    - En littérature, ne fais jamais de **relevé** sans interprétation : un procédé n'a d'intérêt que par l'effet qu'il produit.

    ## 4. Introduction et conclusion
    - **Introduction** : situer le texte (auteur, œuvre, date, contexte) → thème → thèse → problème ou projet de lecture → annonce des mouvements.
    - **Conclusion** : bilan de ce que le texte établit, de la manière dont il le fait, et de son intérêt ; ouverture éventuelle.

    :::attention Les pièges
    - La **paraphrase** : répéter le texte avec d'autres mots.
    - Le **hors-sujet savant** : parler de l'auteur en général au lieu de ce texte.
    - L'oubli de la **fin** du texte, faute de temps : prévois-le dans ton plan.
    :::
  `
});

