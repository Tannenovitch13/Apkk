STUDIUM.methode('version', {
  titre: 'La version (anglais littéraire)',
  resume: 'Traduire un texte littéraire anglais en bon français',
  icone: 'languages',
  contenu: `
    La version consiste à traduire un texte littéraire anglais en **français correct, fidèle et naturel**. Le correcteur sanctionne surtout les **contresens**, les **omissions** et les **fautes de français**.

    ## 1. Comprendre avant de traduire
    - Lis le texte **en entier deux fois**, sans écrire.
    - Repère : le **narrateur** (je / il), le **temps du récit**, le **registre** (soutenu, familier), les **dialogues**.
    - Déduis du contexte le sens des mots inconnus.

    ## 2. Traduire
    - Phrase par phrase, au brouillon. Commence par un premier jet fidèle, puis **réécris en français**.
    - **Temps** : en général *preterit* → **passé simple** (action) ou **imparfait** (description, habitude). Reste cohérent.
    - Respecte l'**ordre des idées** quand c'est possible, mais pas au prix d'un calque.

    ## 3. Relire
    - Relis **ta traduction seule** : se lit-elle comme un texte français ?
    - Vérifie les **accords**, les **conjugaisons** (passé simple !), la **ponctuation des dialogues** (tirets, guillemets français « »).

    :::retenir Les fautes, de la moins grave à la plus grave
    - **Inexactitude** : nuance mal rendue.
    - **Faux-sens** : un mot mal compris, sans gravité pour l'ensemble.
    - **Contresens** : on fait dire au texte autre chose.
    - **Non-sens** : la phrase française n'a pas de sens.
    - **Omission** : très sévèrement sanctionnée. Ne laisse jamais de blanc.
    :::

    :::astuce Procédés de traduction (Vinay et Darbelnet)
    - **Chassé-croisé** : *He swam across the river* → Il traversa la rivière **à la nage**.
    - **Étoffement** : *the man at the door* → l'homme **qui se tenait** à la porte.
    - **Modulation** : changer de point de vue (*It's not difficult* → C'est facile).
    - **Transposition** : changer de catégorie grammaticale (*He came back* → **à son retour**).
    :::
  `
});

